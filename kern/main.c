void secondary_main(int core)
{
    core_flags[core] = 1;
    __asm_flush_dcache_line(&core_flags[core]);

    info("Hello core %d", core);

    // カーネルページアドレスをkpgrに再セット
    set_kpgdir();

    irq_init_gicc(core);
    timer_init(core);
    enable_irq();
    schedule();

    while (1)
        asm volatile("wfi");

}

// (アイドル以外の）最初のタスク, sched_init()で作成される
void init(int arg)
{
    int wpid;
    debug("start arg: 0x%x", arg);
    int pid = copy_process(PF_KTHREAD, (uint64_t)&kernel_process, 0, "kern-1");
    debug("pid: %d", pid);
    assert(pid >= 0);

    while (1) {
        wpid = wait4(0, 0, 0, 0);
        if (wpid < 0) {
            panic("init: wait failed with %d", wpid);
        } else {
            info("wait returns pid=%d", wpid);
        }
    }
}
